var selfTestCAB = uncompressedSelfTestCAB()

func uncompressedSelfTestCAB() []byte {
	// Hand-authored Microsoft CAB with one uncompressed two-byte file.
	name := []byte("payload.txt\x00")
	payload := []byte("ok")
	fileOffset := uint32(44)
	dataOffset := fileOffset + uint32(16+len(name))
	total := dataOffset + 8 + uint32(len(payload))
	buffer := make([]byte, 0, total)
	append16 := func(value uint16) {
		buffer = append(buffer, byte(value), byte(value>>8))
	}
	append32 := func(value uint32) {
		buffer = append(buffer, byte(value), byte(value>>8), byte(value>>16), byte(value>>24))
	}
	buffer = append(buffer, "MSCF"...)
	append32(0)
	append32(total)
	append32(0)
	append32(fileOffset)
	append32(0)
	buffer = append(buffer, 3, 1)
	append16(1)
	append16(1)
	append16(0)
	append16(0)
	append16(0)
	append32(dataOffset)
	append16(1)
	append16(0)
	append32(uint32(len(payload)))
	append32(0)
	append16(0)
	append16(0x21)
	append16(0)
	append16(0x20)
	buffer = append(buffer, name...)
	append32(0)
	append16(uint16(len(payload)))
	append16(uint16(len(payload)))
	buffer = append(buffer, payload...)
	return buffer
}
