function rootOnlyNode(task: TaskDetail, id: string, format: string): FileNodeDetail {
  return fileNode({
    id,
    parent_id: null,
    logical_path: `/${task.original_filename ?? task.name}`,
    display_name: task.original_filename ?? task.name,
    node_type: 'file',
    depth: 0,
    format,
    mime_type: 'application/octet-stream',
    architecture: task.tags.find((tag) => tag.includes('x86')) ?? '',
    size_bytes: task.size_bytes ?? null,
    sha256: task.sha256 ?? '',
    extraction_status: task.status === 'FAILED' ? 'failed' : 'identified',
    error_code: task.error_code?.toLowerCase() ?? '',
    error_message: task.error_message ?? '',
    has_children: false,
    metadata_json: {
      preview_fixture: true,
      current_stage: task.current_stage ?? '',
    },
    source_parent: null,
  })
}

